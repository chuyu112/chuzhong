import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { mkdtemp, mkdir, rm, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { createHash } from 'node:crypto';

const root = process.env.MEDIA_TEST_ROOT || fileURLToPath(new URL('..', import.meta.url));
test('historical creations open in the center, stay private, and remain usable on mobile', { timeout: 60000 }, async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'xiaozhi-media-ui-'));
  const child = spawn(process.execPath, ['server/index.mjs'], { cwd: root, env: { ...process.env, EDU_DATA_DIR: directory, EDU_PORT: '0', EDU_HOST: '127.0.0.1', EDU_COOKIE_SECURE: 'false', CUIYI_SOURCE_DIR: directory }, stdio: ['ignore', 'pipe', 'pipe'] });
  let browser, db;
  try {
    const url = await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('startup timeout')), 15000);
      child.stdout.on('data', value => { const match = String(value).match(/http:\/\/127.0.0.1:\d+/); if (match) { clearTimeout(timer); resolve(match[0]); } });
      child.once('exit', code => { clearTimeout(timer); reject(new Error('exited ' + code)); });
    });
    db = new DatabaseSync(path.join(directory, 'education.sqlite'));
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(url);
    assert.equal((await page.request.get(url + '/api/media')).status(), 401);
    await page.locator('#auth-register-tab').click();
    await page.locator('#auth-phone').fill('19900000042');
    await page.locator('#auth-password').fill('StudentPass123');
    await page.locator('#auth-confirm').fill('StudentPass123');
    await page.locator('#auth-submit').click();
    await page.locator('#chat-welcome').waitFor();
    const { user } = await (await page.request.get(url + '/api/auth/me')).json();
    const png = Buffer.from(await page.evaluate(() => {
      const canvas = document.createElement('canvas'); canvas.width = 900; canvas.height = 540;
      const ctx = canvas.getContext('2d'); ctx.fillStyle = '#eef4eb'; ctx.fillRect(0, 0, 900, 540);
      ctx.fillStyle = '#3c5544'; ctx.font = '38px sans-serif'; ctx.fillText('等式两边，同时减去 5', 80, 110);
      ctx.font = '64px sans-serif'; ctx.fillText('3x + 5 = 20', 230, 260); ctx.fillText('3x = 15', 285, 380);
      return canvas.toDataURL('image/png').split(',')[1];
    }), 'base64');
    const imageHash = createHash('sha256').update(png).digest('hex');
    await mkdir(path.join(directory, 'illustrations', user.id), { recursive: true });
    await writeFile(path.join(directory, 'illustrations', user.id, imageHash), png);
    const mp4 = Buffer.from(await readFile(new URL('./fixtures/media-preview-mp4.base64', import.meta.url), 'utf8'), 'base64'), videoHash = createHash('sha256').update(mp4).digest('hex');
    await mkdir(path.join(directory, 'videos', user.id), { recursive: true });
    await writeFile(path.join(directory, 'videos', user.id, videoHash), mp4);
    const save = (owner, id, messages) => db.prepare('INSERT OR REPLACE INTO documents VALUES (?, ?)').run(`u:${owner}:session:${id}`, JSON.stringify({ id, messages }));
    save(user.id, 'old-image', [{ role: 'user', content: '用图片讲解一元一次方程', at: '2026-10-25T00:00:00Z' }, { role: 'assistant', content: '两边同时减去 5，等式仍然成立。', at: '2026-10-25T00:01:00Z', generatedImageRef: { filename: imageHash, mimeType: 'image/png' } }]);
    save(user.id, 'old-video', [{ role: 'user', content: '英语情景对话：先正常语速，再慢速讲解', at: '2026-10-24T00:00:00Z' }, { role: 'assistant', content: '视频已完成。', at: '2026-10-24T00:01:00Z', generatedVideoRef: { filename: videoHash, mimeType: 'video/mp4' } }]);
    save('other-user', 'secret', [{ role: 'assistant', content: 'other account', generatedImageRef: { filename: imageHash, mimeType: 'image/png' } }]);
    await page.reload(); await page.locator('.media-card').nth(1).waitFor();
    assert.equal(await page.locator('.media-card').count(), 2);
    assert.equal(await page.locator('.brand').innerText(), '小直\n陪你学会每一步');
    const items = (await (await page.request.get(url + '/api/media')).json()).items;
    assert.equal(items.length, 2); assert.doesNotMatch(JSON.stringify(items), /secret|filename|other-user/);
    assert.equal((await page.request.get(url + '/api/sessions/secret/images/0')).status(), 404);
    await page.waitForFunction(() => document.querySelector('#media-stage img')?.naturalWidth === 900);
    const sidebar = await page.locator('.sidebar').boundingBox(), preview = await page.locator('.media-preview').boundingBox(), chat = await page.locator('.chat-workspace').boundingBox();
    assert.ok(sidebar.x + sidebar.width <= preview.x + 1); assert.ok(preview.x + preview.width <= chat.x + 1);
    assert.ok((await page.locator('#send-chat').boundingBox()).y < 900);
    await page.evaluate(() => document.body.dataset.theme = 'night');
    await mkdir(path.join(root, 'artifacts'), { recursive: true });
    await page.screenshot({ animations: 'disabled', path: path.join(root, 'artifacts/media-workspace-desktop.png') });
    await page.locator('[data-media-filter="video"]').click();
    await page.waitForFunction(() => document.querySelector('#media-stage video')?.readyState >= 2);
    await page.locator('#media-stage video').evaluate(video => video.play());
    assert.ok(await page.locator('#media-download').getAttribute('href').then(href => href.endsWith('?download=1')));
    await page.locator('[data-media-filter="image"]').click();
    await page.locator('#media-stage img').waitFor();
    await page.locator('#media-refresh').click();
    assert.equal(await page.locator('.media-card').count(), 1);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.locator('.media-preview').isVisible(), false);
    assert.ok((await page.locator('#send-chat').boundingBox()).y < 844);
    await page.locator('[data-workspace-pane="preview"]').click();
    assert.equal(await page.locator('.chat-workspace').isVisible(), false);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ animations: 'disabled', path: path.join(root, 'artifacts/media-workspace-mobile.png') });
    await page.locator('[data-workspace-pane="chat"]').click();
    await page.locator('#nav-toggle').click();
    await page.locator('.conversation-item', { hasText: '用图片讲解' }).click();
    await page.locator('.generated-media-link', { hasText: '查看图片' }).click();
    await page.locator('#media-stage img').waitFor();
    assert.equal(await page.locator('.media-preview').isVisible(), true);
    assert.deepEqual(errors, []);
  } finally {
    await browser?.close(); db?.close();
    if (child.exitCode === null) await new Promise(resolve => { child.once('exit', resolve); child.kill('SIGTERM'); });
    await rm(directory, { recursive: true, force: true });
  }
});
